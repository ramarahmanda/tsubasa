"""Two guards that must not be built out of tool-name allowlists.

Why not an allowlist. A Bash allowlist pattern like `Bash(git log:*)` matches
only commands that literally begin `git log`. Everything an agent actually
emits against a multi-repo workspace is `git -C <repo> log ...` or
`cd <repo> && git log ...`, and those are denied. A denial is invisible in the
answer text: it shows up as a retry loop and a hedged reply, which reads
exactly like a genuine evidence gap. Applied to this benchmark that would zero
out g-git-history, the one category where distilled history can beat plain
file reading, and publish "study adds nothing" for a reason that has nothing
to do with study.

So Bash is granted wholesale and the two properties that actually matter are
enforced where they cannot collide with git:

  1. the arms must not mutate the graph they are being measured on.
     Enforced with a query-only `tsubasa` shim placed first on PATH, plus an
     after-the-fact fingerprint of the graph. A shim decides on the parsed
     subcommand, so `cd x && tsubasa event add` is caught where a prefix
     pattern would miss it.
  2. a permission denial must never be mistaken for a capability gap.
     Every denied tool call is counted, recorded in the run JSON, and shown
     in the summary.
"""

from __future__ import annotations

import hashlib
import os
import shutil
from pathlib import Path

# Subcommands that only read. `tsubasa source detect` is excluded: it can
# write captain.toml. Anything not listed is refused by the shim.
QUERY_ONLY = {
    "query": None,
    "questions": None,
    "vocab": None,
    "doctor": None,
    "task": {"list"},
    "goal": {"list"},
    "source": {"list"},
}

SHIM = r"""#!/bin/sh
# Generated by benchmark/harness/guard.py. Query-only tsubasa for benchmark
# runs: an arm may read the graph it is measured against, never write to it.
log() { printf '%s\t%s\n' "$1" "$*" >> "$TSUBASA_BENCH_GUARD_LOG" 2>/dev/null; }
sub="$1"; arg="$2"
case "$sub" in
__CASES__
esac
log DENIED "$@"
echo "tsubasa: '$sub $arg' is disabled during a benchmark run (query-only guard)." >&2
exit 77
"""


def _cases() -> str:
    lines = []
    for cmd, subs in sorted(QUERY_ONLY.items()):
        if subs is None:
            lines.append(f'  {cmd}) exec "$TSUBASA_BENCH_REAL" "$@" ;;')
        else:
            pattern = "|".join(sorted(subs))
            lines.append(
                f'  {cmd}) case "$arg" in {pattern}) exec "$TSUBASA_BENCH_REAL" "$@" ;; esac ;;')
    return "\n".join(lines)


def write_query_only_shim(bin_dir: Path, log_path: Path) -> dict:
    """Create <bin_dir>/tsubasa. Returns the env additions the child needs."""
    real = shutil.which("tsubasa")
    bin_dir.mkdir(parents=True, exist_ok=True)
    shim = bin_dir / "tsubasa"
    shim.write_text(SHIM.replace("__CASES__", _cases()))
    shim.chmod(0o755)
    log_path.parent.mkdir(parents=True, exist_ok=True)
    return {
        "PATH": os.pathsep.join([str(bin_dir), os.environ.get("PATH", "")]),
        "TSUBASA_BENCH_REAL": real or "/nonexistent/tsubasa",
        "TSUBASA_BENCH_GUARD_LOG": str(log_path),
    }


def read_guard_log(log_path: Path) -> list[str]:
    if not log_path.is_file():
        return []
    return [ln for ln in log_path.read_text().splitlines() if ln.strip()]


# ---------------------------------------------------------------- graph state

GRAPH_FILES = ("graph/entities.toon", "graph/relations.toon", "graph/aliases.toon",
               "graph/profiles.toon", "graph/anchors.toon", "graph/code.toon",
               "memory/hot.md", "memory/index.md", "state.toon")


def graph_fingerprint(fixture: Path) -> str:
    """Content hash of everything an arm could plausibly write to. Compared
    across a run: a change means the arm mutated its own scoreboard."""
    base = fixture / ".tsubasa"
    digest = hashlib.sha256()
    for rel in GRAPH_FILES:
        path = base / rel
        digest.update(rel.encode())
        digest.update(path.read_bytes() if path.is_file() else b"")
    events = base / "graph" / "events"
    for path in sorted(events.rglob("*.toon")) if events.is_dir() else []:
        digest.update(str(path.relative_to(base)).encode())
        digest.update(path.read_bytes())
    tasks = base / "tasks"
    for path in sorted(tasks.rglob("*.toon")) if tasks.is_dir() else []:
        digest.update(str(path.relative_to(base)).encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


# ------------------------------------------------------------ denial probing

# Command forms an agent actually emits against a multi-repo workspace. The
# probe asks a live session to run each one and report the outcome, so the
# permission configuration is verified rather than assumed.
PROBE_COMMANDS = (
    "git -C postgres log -1 --format=%H",
    "cd postgres && git log -1 --format=%H",
    "git -C postgres show --no-patch --format=%s f4c7c410ee",
    "git -C postgres rev-list -n 1 HEAD",
    "git -C postgres cat-file -e f4c7c410ee^{commit} && echo OK",
    "git -C etcd log --oneline -1",
    "grep -rn 'half-dead' postgres/src/backend/access/nbtree/README | head -2",
)

PROBE_PROMPT = """\
Run each of these shell commands exactly as written, one at a time. Do not \
rewrite, combine or substitute them.

IMPORTANT: your shell keeps its working directory between commands, and one of \
these commands changes it. Return to the starting directory before each command \
so that every one of them runs from there. Report the command exactly as it is \
written below, not with your `cd` prefix.

{commands}

Then reply with one line per command in the form:
<command> => RAN <first line of output>
or
<command> => BLOCKED <the refusal you received>

No other text.
"""

# Output that means the command executed but did not do its job. Distinct from
# BLOCKED, and NOT acceptable either: the probe exists to prove these exact
# command forms work, and "ran, produced fatal:" proves the opposite.
BROKEN_SIGNATURES = ("fatal:", "no such file", "not a git repository",
                     "command not found", "cannot change to")
# OS-level refusals. These ARE permission problems even though the wording
# differs from Claude Code's own refusal text.
BLOCKED_SIGNATURES = ("permission denied", "operation not permitted", "blocked")


def probe_prompt() -> str:
    return PROBE_PROMPT.format(commands="\n".join(PROBE_COMMANDS))


def probe_verdict(answer: str) -> dict:
    """Every probe command must come back RAN with real output.

    Three outcomes, kept apart because they have different causes and different
    fixes: `blocked` means the permission configuration would silently zero out
    a category; `broken` means the command executed and failed (a wrong working
    directory, a missing clone) which invalidates the probe just as thoroughly;
    `ran` is the only acceptable one.
    """
    results = {}
    for cmd in PROBE_COMMANDS:
        line = next((ln for ln in answer.splitlines() if cmd in ln), "")
        low = line.lower()
        if not line:
            results[cmd] = "no report"
        elif "BLOCKED" in line.upper() or any(s in low for s in BLOCKED_SIGNATURES):
            results[cmd] = "blocked"
        elif any(s in low for s in BROKEN_SIGNATURES):
            results[cmd] = "broken"
        elif "RAN" in line.upper():
            results[cmd] = "ran"
        else:
            results[cmd] = "no report"
    blocked = sorted(c for c, v in results.items() if v == "blocked")
    broken = sorted(c for c, v in results.items() if v in ("broken", "no report"))
    return {"ok": not blocked and not broken, "blocked": blocked, "broken": broken,
            "results": results}
