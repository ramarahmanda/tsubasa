"""Deterministic fake session, for the dry run.

The stub writes a real stream-json file, so everything downstream of the
transport is exercised unchanged: stream parsing, contamination postflight,
citation extraction and resolution against the real fixture on disk, judging,
resumability, summarising.

What it deliberately does NOT do is imitate answer quality. Arm B's stub
answer cites the question's own locator (so those citations resolve), arm A's
cites a mangled version of it (so those do not). That is a fixed rule, not a
measurement, and every artifact it produces carries stub=true.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import citations
from config import PERSONA_MARKER

STUB_TOOLS = ["Bash", "Read", "Grep", "Glob", "TodoWrite"]


def _mangle(path: str) -> str:
    parts = path.split("/")
    return "/".join(parts[:-1] + ["legacy", parts[-1]]) if len(parts) > 1 else f"legacy/{path}"


def _cited(question, arm: str) -> list[str]:
    """Citation strings for the stub answer, derived from the locator."""
    cites = citations.extract(question.locator or "")
    out: list[str] = []
    for cite in cites:
        raw = cite["raw"]
        if arm == "B":
            out.append(raw)
        elif cite["kind"] in ("path", "file_line"):
            out.append(_mangle(raw))
        elif cite["kind"] == "sha":
            out.append("deadbee" + raw[7:] if len(raw) > 7 else "deadbeef")
        else:
            out.append(raw)
    return out[:6]


def _answer(question, arm: str, turn: int = 1) -> str:
    cited = _cited(question, arm)
    body = "\n".join(f"- {c}" for c in cited) or "- (no citation)"
    again = "" if turn == 1 else f" (retry {turn} after a nudge)"
    if arm == "B":
        return (f"[STUB captain answer for {question.qid}]{again} Evidence:\n{body}\n"
                f"This text is generated by the dry-run stub and grades nothing.")
    return (f"[STUB vanilla answer for {question.qid}]{again} Probably:\n{body}\n"
            f"This text is generated by the dry-run stub and grades nothing.")


def _tokens(question, arm: str) -> dict:
    seed = int(hashlib.sha256(f"{question.qid}{arm}".encode()).hexdigest()[:6], 16)
    return {
        "input_tokens": 1200 + seed % 400,
        "output_tokens": 300 + seed % 200,
        "cache_creation_input_tokens": 4000 + seed % 2000,
        "cache_read_input_tokens": 20000 + seed % 9000,
    }


def _turn_messages(question, arm: str, model: str, turn: int,
                   contaminate: bool = False) -> list[dict]:
    """The messages one stub turn emits, in the shapes the real CLI emits.

    Hook events carry the real subtypes (`hook_started` / `hook_response`),
    checked against claude 2.1.220, so the contamination postflight is
    exercised against the shape it will actually meet.
    """
    answer = _answer(question, arm, turn)
    usage = _tokens(question, arm)
    slash = ["/init", "/review"]
    skills: list[str] = []
    if arm == "B":
        tsubasa_skills = ["tsubasa:recall", "tsubasa:capture", "tsubasa:delegate"]
        slash += tsubasa_skills
        skills += tsubasa_skills

    messages: list[dict] = []
    if turn == 1:
        messages.append({
            "type": "system", "subtype": "init", "session_id": f"stub-{question.qid}-{arm}",
            "cwd": "(stub)", "model": model, "tools": STUB_TOOLS,
            "slash_commands": slash, "skills": skills, "agents": [],
            # the real CLI lists installed plugins here even under --safe-mode,
            # where they are inert; the stub reproduces that so the postflight
            # distinction between "installed" and "active" is exercised
            "plugins": [{"name": "tsubasa", "source": "tsubasa@tsubasa", "version": "0.1.16"}],
            "mcp_servers": [], "permissionMode": "bypassPermissions",
        })
        # Arm B's SessionStart hook injects the persona; the stub reproduces the
        # marker so the postflight check has something real to find.
        if arm == "B" or contaminate:
            messages += [
                {"type": "system", "subtype": "hook_started", "hook_name": "SessionStart:startup",
                 "hook_event": "SessionStart", "session_id": f"stub-{question.qid}-{arm}"},
                {"type": "system", "subtype": "hook_response", "hook_name": "SessionStart:startup",
                 "hook_event": "SessionStart", "exit_code": 0, "outcome": "success",
                 "output": f"{PERSONA_MARKER}tsubasa-benchmark (Principal Engineer) of this repo.",
                 "session_id": f"stub-{question.qid}-{arm}"},
            ]
        messages.append({"type": "rate_limit_event", "session_id": f"stub-{question.qid}-{arm}",
                         "rate_limit_info": {"status": "allowed", "rateLimitType": "five_hour"}})
    messages += [
        {"type": "assistant", "message": {"role": "assistant", "content": [
            {"type": "tool_use", "id": f"t{turn}1", "name": "Grep",
             "input": {"pattern": question.qid, "path": "."}}]}},
        {"type": "user", "message": {"role": "user", "content": [
            {"type": "tool_result", "tool_use_id": f"t{turn}1", "content": "(stub result)"}]}},
        {"type": "assistant", "message": {"role": "assistant", "content": [
            {"type": "tool_use", "id": f"t{turn}2", "name": "Read",
             "input": {"file_path": (question.locator or "README.md").split(";")[0].strip()}}]}},
        {"type": "user", "message": {"role": "user", "content": [
            {"type": "tool_result", "tool_use_id": f"t{turn}2", "content": "(stub result)"}]}},
        {"type": "assistant", "message": {"role": "assistant",
                                          "content": [{"type": "text", "text": answer}]}},
        {"type": "result", "subtype": "success", "is_error": False,
         "duration_ms": 1000 + (usage["output_tokens"] % 500), "num_turns": 3,
         "result": answer, "total_cost_usd": 0.0, "usage": usage,
         "session_id": f"stub-{question.qid}-{arm}", "stub": True},
    ]
    return messages


def write_stream(stream_path: Path, question, arm: str, model: str,
                 contaminate: bool = False) -> None:
    """A single-turn stub stream."""
    messages = _turn_messages(question, arm, model, 1, contaminate=contaminate)
    stream_path.parent.mkdir(parents=True, exist_ok=True)
    stream_path.write_text("".join(json.dumps(m, sort_keys=True) + "\n" for m in messages))


class StubSession:
    """Same surface as model.Session, so the follow-up loop is exercised by the
    dry run without a model call. Costs are zero: a dry run measures plumbing,
    never quality, and nothing it writes may look like a result."""

    def __init__(self, question, arm: str, model: str, stream_path: Path,
                 contaminate: bool = False):
        self.question, self.arm, self.model = question, arm, model
        self.contaminate = contaminate
        stream_path.parent.mkdir(parents=True, exist_ok=True)
        self.stream_path = stream_path
        self._sink = stream_path.open("w")
        self.turn = 0
        self.stderr = ""
        self.timed_out = False

    def ask(self, _text: str) -> dict:
        self.turn += 1
        messages = _turn_messages(self.question, self.arm, self.model, self.turn,
                                  contaminate=self.contaminate)
        for msg in messages:
            self._sink.write(json.dumps(msg, sort_keys=True) + "\n")
        self._sink.flush()
        result = next((m for m in messages if m.get("type") == "result"), {})
        return {"messages": messages, "result": result, "seconds": 0.0,
                "timed_out": False, "eof": False}

    def close(self) -> dict:
        self._sink.close()
        return {"returncode": 0, "stderr": "", "wall_clock_s": 0.0}
